export const AuditOutcomeSchema = z.enum(["SUCCESS", "FAILURE", "DENIED"]);

export const AuditRecordSchema = z
  .object({
    id: z.string().uuid(),
    eventType: AuditEventTypeSchema,
    timestamp: z.iso.datetime(),
    userId: z.string().uuid().nullable(),
    companyId: z.string().uuid().nullable().default(null),
    deviceId: z.string().uuid().nullable(),
    ipAddress: z.string().min(1),
    outcome: AuditOutcomeSchema,
    reason: z.string().trim().min(1).max(500),
    requestId: z.string().min(1),
    metadata: z
      .record(z.string().trim().min(1).max(80), z.json())
      .refine(
        (value) =>
          Object.keys(value).length <= 25 && JSON.stringify(value).length <= 4_096,
        "Audit metadata must remain bounded.",
      )
      .optional(),
  })
  .strict();

export const AuditListResponseSchema = z.array(AuditRecordSchema);

export type AuditEventType = z.infer<typeof AuditEventTypeSchema>;
export type AuditOutcome = z.infer<typeof AuditOutcomeSchema>;
export type AuditRecord = z.infer<typeof AuditRecordSchema>;
